"""Proof-Carrying Text (O8) Verifier.

Implements the deterministic verification part of the A2A loop:
Agent A (Certified Proposer, LLM) -> Agent B (Formal Verifier, Deterministic Code).
"""

from __future__ import annotations

import hashlib
import json
import logging
from dataclasses import dataclass
from typing import Any

logger = logging.getLogger(__name__)

@dataclass
class PCTCertificate:
    """Proof-Carrying Text Certificate."""
    text_hash: str
    spans: list[dict[str, Any]]
    banned_words_clean: bool


import re

_NUMERIC_METRIC_RE = re.compile(
    r"(?:\$\d+(?:\.\d+)?\s*(?:[MBK]|million|billion)?|\b\d+(?:\.\d+)?%|\b\d+(?:\.\d+)?x\b)",
    re.IGNORECASE,
)


def build_pct_certificate(
    generated_text: str,
    claimed_fact_ids: list[str],
    source_facts: dict[str, str] | None = None,
    banned_words_clean: bool = True,
) -> dict[str, Any]:
    """Construct a deterministic PCTCertificate payload for generated text."""
    text_hash = hashlib.sha256(generated_text.encode("utf-8")).hexdigest()
    span: dict[str, Any] = {
        "text": generated_text,
        "claimed_fact_ids": list(claimed_fact_ids),
    }
    if source_facts:
        combined = " ".join(source_facts.get(fid, "") for fid in claimed_fact_ids)
        span["entailed_metrics"] = _NUMERIC_METRIC_RE.findall(combined)
    return {
        "text_hash": text_hash,
        "spans": [span],
        "banned_words_clean": banned_words_clean,
    }


def verify_pct_certificate(
    generated_text: str,
    certificate_data: dict[str, Any],
    allowed_fact_ids: set[str],
    source_facts: dict[str, str] | None = None,
) -> bool:
    """Deterministically verify a Proof-Carrying Text certificate in <1ms.
    
    Args:
        generated_text: The raw text generated by the LLM proposer.
        certificate_data: The JSON payload claimed by the LLM as proof.
        allowed_fact_ids: The set of assertion IDs the LLM was allowed to use.
        source_facts: Optional mapping of fact_id -> raw fact text for numeric entailment verification.
    
    Returns:
        True if the proof holds mathematically; False otherwise.
    """
    if not certificate_data:
        return False
        
    try:
        cert = PCTCertificate(
            text_hash=certificate_data.get("text_hash", ""),
            spans=certificate_data.get("spans", []),
            banned_words_clean=certificate_data.get("banned_words_clean", False)
        )
    except (TypeError, ValueError, AttributeError):
        return False

    if not cert.banned_words_clean:
        logger.error("PCT Verification Failed: banned_words_clean is False.")
        return False

    # 1. Cryptographic text match (ensure proof belongs to THIS text)
    actual_hash = hashlib.sha256(generated_text.encode("utf-8")).hexdigest()
    if cert.text_hash != actual_hash:
        logger.error("PCT Verification Failed: Hash mismatch.")
        return False

    # 2. Entailment check: All claimed assertion IDs must be in the allowed set
    claimed_union: list[str] = []
    entailed_metrics_pool: list[str] = []
    for span in cert.spans:
        claimed_ids = span.get("claimed_fact_ids", [])
        for cid in claimed_ids:
            if cid not in allowed_fact_ids:
                logger.error(f"PCT Verification Failed: Fact ID {cid} not in allowed set.")
                return False
            claimed_union.append(str(cid))
        for m in span.get("entailed_metrics") or []:
            entailed_metrics_pool.append(str(m).lower().strip())

    # 3. Numeric preservation: extract numbers/metrics from generated_text and verify against source facts or span entailed_metrics
    text_metrics = [m.lower().strip() for m in _NUMERIC_METRIC_RE.findall(generated_text)]
    if text_metrics:
        if source_facts is not None:
            allowed_source_blob = " ".join(
                str(source_facts.get(fid, "")) for fid in (claimed_union or list(allowed_fact_ids))
            ).lower()
            for tm in text_metrics:
                if tm not in allowed_source_blob:
                    logger.error(f"PCT Verification Failed: Unentailed metric '{tm}' in generated text.")
                    return False
        elif entailed_metrics_pool or any("entailed_metrics" in s for s in cert.spans):
            allowed_metric_blob = " ".join(entailed_metrics_pool).lower()
            for tm in text_metrics:
                if tm not in allowed_metric_blob:
                    logger.error(f"PCT Verification Failed: Metric '{tm}' not entailed by certificate spans.")
                    return False

    return True
